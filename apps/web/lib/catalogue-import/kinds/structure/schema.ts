import {
  STRUCTURE_RELATIONSHIP_KINDS,
  STRUCTURE_SECTION_KEYS,
} from "../../../catalogue/structure-vocabulary.ts";
import {
  ACADEMIC_STRUCTURE_EXTRACTION_SCHEMA_VERSION,
  ACADEMIC_STRUCTURE_KINDS,
} from "./contract.ts";

const nullableNumberSchema = { type: ["number", "null"], minimum: 0 };
